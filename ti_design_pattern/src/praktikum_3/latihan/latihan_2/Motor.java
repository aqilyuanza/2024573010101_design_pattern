package praktikum_3.latihan.latihan_2;

public class Motor {
    // Atribut private
    private String merk;
    private int tahun;
    // Getter dan Setter untuk merk
    public String getMerk() {
        return merk;
    }
    public void setMerk(String merk) {
        this.merk = merk;
    }
    // Getter dan Setter untuk tahun
    public int getTahun() {
        return tahun;
    }
    public void setTahun(int tahun) {
        this.tahun = tahun;
    }
}
